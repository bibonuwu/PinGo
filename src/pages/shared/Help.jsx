export default function Help() {
  const { user } = useAuth();
  const [open, setOpen] = useState(0);
  const items = FAQ[user.role] ?? FAQ.parent;
  return (
    <div className="page help">
      <PageHeader back={`/${user.role}${user.role === 'admin' ? '/settings' : '/profile'}`} title="Помощь" />
      <PingoGuide mood="happy" bubbleKey="help">
        Я собрал ответы на частые вопросы. Если не нашли нужного — напишите нам, ответим в течение дня.
      </PingoGuide>
      <ul className="faq">
        {items.map(([q, a], i) => (
          <li key={q} className={cx('faq__item', open === i && 'is-open')}>
            <button type="button" className="faq__q" aria-expanded={open === i} onClick={() => setOpen(open === i ? -1 : i)}>
              {q}
              <CaretDownIcon size={20} weight="bold" />
            </button>
            <AnimatePresence initial={false}>
              {open === i && (
                <motion.div className="faq__a" initial={{ height: 0, opacity: 0 }} animate={{ height: 'auto', opacity: 1 }} exit={{ height: 0, opacity: 0 }}>
                  <p>{a}</p>
                </motion.div>
              )}
            </AnimatePresence>
          </li>
        ))}
      </ul>
      <a className="btn btn--soft btn--lg btn--block" href="mailto:support@pingo.app?subject=Вопрос%20о%20Pingo">
        <EnvelopeSimpleIcon size={20} weight="bold" />
        <span>Написать в поддержку</span>
      </a>
    </div>
  );
}
